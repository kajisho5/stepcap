def check_lang(lang: str) -> str:
    if lang not in LANGS:
        raise ValueError(f"unsupported language {lang!r}; choose from {', '.join(LANGS)}")
    return lang


def text(lang: str, key: str, **kw: Any) -> str:
    return T[lang][key].format(**kw)


def format_keys(keys: str) -> str:
    parts = keys.split("+")
    return "+".join(KEY_LABELS.get(p, p.upper() if len(p) == 1 else p.capitalize()) for p in parts)


def window_label(ev: dict[str, Any]) -> str | None:
    label = (ev.get("window_title") or ev.get("app_name") or "").strip()
    label = " ".join(label.split())
    if not label:
        return None
    if len(label) > MAX_WINDOW_LABEL:
        label = label[: MAX_WINDOW_LABEL - 1].rstrip() + "…"
    return label


def _with_window(lang: str, key: str, ev: dict[str, Any], **kw: Any) -> str:
    w = window_label(ev)
    if w:
        return text(lang, key, w=w, **kw)
    return text(lang, key + "_nw", **kw)


def auto_title(ev: dict[str, Any], lang: str = "en") -> str:
    kind = ev.get("kind")
    if kind == "click":
        ct = ev.get("click_type", "single")
        if ct not in ("single", "double", "right", "middle"):
            ct = "single"
        return _with_window(lang, f"click_{ct}", ev)
    if kind == "type":
        return _with_window(lang, "type", ev)
    if kind == "drag":
        return _with_window(lang, "drag", ev)
    if kind == "scroll":
        d = text(lang, ev.get("direction", "down"))
        return _with_window(lang, "scroll", ev, dir=d)
    if kind == "key":
        return _with_window(lang, "key", ev, keys=format_keys(ev.get("keys", "")))
    if kind == "manual":
        note = (ev.get("note") or "").strip()
        first = note.splitlines()[0].strip() if note else ""
        return first or text(lang, "manual_nw")
    return _with_window(lang, "click_single", ev)


def auto_description(ev: dict[str, Any], lang: str = "en") -> str:
    kind = ev.get("kind")
    if kind == "type":
        enter = bool(ev.get("enter"))
        if ev.get("masked", True) or "text" not in ev:
            if not ev.get("chars"):
                return text(lang, "pressed_enter") if enter else ""
            key = "typed_masked_enter" if enter else "typed_masked"
            return text(lang, key, n=ev.get("chars", 0))
        key = "typed_text_enter" if enter else "typed_text"
        return text(lang, key, text=ev.get("text", ""))
    if kind == "scroll":
        return text(
            lang, "scrolled", dir=text(lang, ev.get("direction", "down")), amount=ev.get("amount")
        )
    if kind == "manual":
        note = (ev.get("note") or "").strip()
        lines = note.splitlines()
        return "\n".join(lines[1:]).strip() if len(lines) > 1 else ""
    return ""


def heading(n: int, title: str, lang: str = "en") -> str:
    return text(lang, "heading", n=n, title=title)
